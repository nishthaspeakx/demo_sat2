/** Animated 3-bar waveform (listening cue). */
export function Waveform({ color = "#fff" }) {
  const delays = [0, 0.15, 0.3, 0.15];
  return (
    <span className="flex h-5 items-center gap-[3px]" aria-hidden>
      {delays.map((d, i) => (
        <span key={i} className="wave-bar h-full w-[3px] rounded-full"
          style={{ backgroundColor: color, animationDelay: `${d}s` }} />
      ))}
    </span>
  );
}
